import { openContinuousEditor, openModuleSettings } from './helpers/editor'
import { test, expect } from '@playwright/test'

test('compose text, images and text inline, reorder pictures and preserve titles after saving', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '编辑名片', exact: true }).click()
  await openContinuousEditor(page, { pages: true })
  await page.getByRole('button', { name: '＋ 添加页面', exact: true }).click()
  await page.getByRole('button', { name: '第 2 页自由图文', exact: true }).click()
  const group = page.locator('.module-group').nth(1)
  await group.locator('.page-row input').fill('品牌故事')
  await page.getByRole('button', { name: '第 2 页开头插入文字', exact: true }).click()
  const rows = group.locator('.module-row')
  await rows.nth(0).locator('textarea').fill('从一个想法开始。')
  await openModuleSettings(rows.nth(0))
  await rows.nth(0).getByRole('button', { name: '模块 3 显示标题', exact: true }).click()
  await rows.nth(0).locator('input').fill('我们的故事')
  await page.getByRole('button', { name: '模块 3 后插入图片', exact: true }).click()
  const fixtures = await page.evaluate(() => ['#234e3e', '#c7522f'].map(color => {
    const canvas = document.createElement('canvas'); canvas.width = 480; canvas.height = 240
    const context = canvas.getContext('2d')!; context.fillStyle = color; context.fillRect(0, 0, 480, 240)
    return canvas.toDataURL('image/png').split(',')[1]
  }))
  const chooser = page.waitForEvent('filechooser')
  await rows.nth(1).getByRole('button', { name: '上传图片', exact: true }).click()
  await (await chooser).setFiles(fixtures.map((data, i) => ({ name: `story-${i}.png`, mimeType: 'image/png', buffer: Buffer.from(data, 'base64') })))
  await expect(rows.nth(1).locator('.image-thumbnail')).toHaveCount(2)
  await expect(rows.nth(1).getByRole('button', { name: '上传图片', exact: true })).toBeEnabled()
  const before = await rows.nth(1).locator('.image-thumbnail img').evaluateAll(images => images.map(image => (image as HTMLImageElement).src))
  await rows.nth(1).getByRole('button', { name: '前移图片 2', exact: true }).click()
  await expect.poll(() => rows.nth(1).locator('.image-thumbnail img').evaluateAll(images => images.map(image => (image as HTMLImageElement).src))).toEqual([...before].reverse())
  await page.getByRole('button', { name: '模块 4 后插入文字', exact: true }).click()
  await rows.nth(2).locator('textarea').fill('期待与你创造下一段故事。')
  await page.getByRole('button', { name: '模块 3 后插入文字', exact: true }).click()
  await rows.nth(1).locator('textarea').fill('每一步都用心。')
  await rows.nth(1).getByRole('button', { name: '下移模块 4', exact: true }).click()
  await page.getByRole('button', { name: '预览名片', exact: true }).click()
  const preview = page.locator('.live-preview')
  await expect(preview.locator('.section-title')).toHaveText(['我们的故事'])
  await expect(preview.locator('.section-content')).toHaveText(['从一个想法开始。', '每一步都用心。', '期待与你创造下一段故事。'])
  await expect(preview.locator('.profile-section').nth(1).locator('.gallery-image')).toHaveCount(2)
  await expect(preview.locator('.gallery-grid')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await preview.screenshot({ path: 'artifacts/freeform-article-preview.png' })
  await page.getByRole('button', { name: '保存我的名片', exact: true }).click()
  await expect(page.getByRole('button', { name: '分享名片', exact: true })).toBeVisible()
  await page.reload()
  await page.locator('.page-tabs').getByRole('button', { name: '品牌故事', exact: true }).click()
  await expect(page.locator('.profile-section .section-title')).toHaveText(['我们的故事'])
  await expect(page.locator('.profile-section').nth(1).locator('.gallery-image')).toHaveCount(2)
  await page.getByRole('button', { name: '编辑名片', exact: true }).click()
  await openContinuousEditor(page, { pages: true })
  await expect(group.locator('.module-row')).toHaveCount(4)
  await openModuleSettings(group.locator('.module-row').first())
  await openModuleSettings(group.locator('.module-row').nth(1))
  await expect(group.locator('.module-row').first().getByRole('button', { name: /显示标题/ })).toHaveAttribute('aria-pressed', 'true')
  await expect(group.locator('.module-row').nth(1).getByRole('button', { name: /显示标题/ })).toHaveAttribute('aria-pressed', 'false')
})
