import { dragModule, openContinuousEditor } from './helpers/editor'
import { test, expect, type Page } from '@playwright/test'

function field(page: Page, label: string) {
  return page.locator('.field').filter({ has: page.getByText(label, { exact: true }) }).locator('input')
}

test('customize appearance, preview, reload and share the same design with visitors', async ({ page, browser }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '编辑名片', exact: true }).click()
  await openContinuousEditor(page, { appearance: true })
  await page.getByRole('button', { name: '居中名片', exact: false }).click()
  await field(page, '自定义主题色').fill('#f4d35e')
  await field(page, '封面小标题').fill('HELLO FROM MY STUDIO')
  await page.locator('.field').filter({ has: page.getByText('封面文案', { exact: true }) }).locator('textarea').fill('用设计连接\n新的可能')
  await field(page, '底部署名').fill('MY STUDIO')
  await page.getByRole('button', { name: '圆形', exact: true }).click()
  await page.getByRole('button', { name: '公司 / 组织 · 展示', exact: true }).click()
  await page.getByRole('button', { name: '专业标签 · 展示', exact: true }).click()
  await page.getByRole('button', { name: '预览名片', exact: true }).click()
  const preview = page.locator('.identity-card')
  await expect(preview).toHaveClass(/centered/)
  await expect(preview).toHaveClass(/avatar-circle/)
  await expect(preview.locator('.card-company')).toHaveCount(0)
  await expect(preview.locator('.tag')).toHaveCount(0)
  await expect(preview.locator('.cover-title')).toHaveText('用设计连接\n新的可能', { useInnerText: true })
  await expect(preview.locator('.card-cover')).toHaveCSS('background-color', 'rgb(244, 211, 94)')
  await expect(preview.locator('.card-cover')).toHaveCSS('color', 'rgb(23, 37, 29)')
  await page.screenshot({ path: 'artifacts/custom-preview-mobile.png', fullPage: true })
  await page.getByRole('button', { name: '保存我的名片' }).click()
  await expect(page.getByRole('button', { name: '分享名片', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.locator('.identity-card')).toHaveClass(/centered/)
  await expect(page.locator('.cover-title')).toHaveText('用设计连接\n新的可能', { useInnerText: true })
  await page.getByRole('button', { name: '访客视角' }).click()
  const guest = await browser.newContext()
  try {
    const guestPage = await guest.newPage()
    await guestPage.goto(page.url())
    await expect(guestPage.locator('.identity-card')).toHaveClass(/avatar-circle/)
    await expect(guestPage.locator('.card-wordmark')).toHaveText('MY STUDIO')
    await expect(guestPage.locator('.card-company')).toHaveCount(0)
    await expect(guestPage.locator('.card-cover')).toHaveCSS('background-color', 'rgb(244, 211, 94)')
  }
  finally { await guest.close() }
  await page.getByRole('button', { name: '编辑我的名片', exact: true }).click()
  await openContinuousEditor(page, { appearance: true })
  await expect(field(page, '公司 / 组织')).toHaveValue('未止设计 · UNFOLD STUDIO')
  await page.getByRole('button', { name: '恢复默认风格', exact: true }).click()
  await page.getByRole('button', { name: '预览名片', exact: true }).click()
  await expect(page.locator('.identity-card')).toHaveClass(/classic/)
  await expect(page.locator('.card-company')).toHaveText('未止设计 · UNFOLD STUDIO')
  await expect(field(page, '自定义主题色')).toHaveValue('')
  await page.getByRole('button', { name: '简约名片', exact: false }).click()
  await expect(page.locator('.identity-card')).toHaveClass(/minimal/)
})

test('build a personal profile with drag sorting, mobile sorting and custom modules', async ({ page, browser }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/')
  await page.getByRole('button', { name: '编辑名片', exact: true }).click()
  await openContinuousEditor(page)
  await page.getByRole('button', { name: '＋ 添加文字段落', exact: true }).click()
  const rows = page.locator('.module-row')
  await rows.nth(2).locator('input').fill('我的服务')
  await rows.nth(2).locator('textarea').fill('品牌策略\n网站与小程序设计')
  const customId = await rows.nth(2).getAttribute('data-module-id')
  await dragModule(page, rows.nth(2).locator('.drag-handle'), rows.nth(0).locator('.drag-handle'))
  await expect(rows.nth(0)).toHaveAttribute('data-module-id', customId!)
  await expect(page.locator('.profile-section .section-title')).toHaveText(['我的服务', '关于我', '保持联系'])
  await page.screenshot({ path: 'artifacts/profile-editor-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '下移模块 1', exact: true }).click()
  await expect(rows.nth(1)).toHaveAttribute('data-module-id', customId!)
  await page.getByRole('button', { name: '隐藏模块 1', exact: true }).click()
  await page.getByRole('button', { name: '＋ 添加文字段落', exact: true }).click()
  await expect(rows).toHaveCount(4)
  await page.getByRole('button', { name: '删除模块 4', exact: true }).click()
  await expect(rows).toHaveCount(3)
  await page.getByRole('button', { name: '预览名片', exact: true }).click()
  await expect(page.locator('.profile-section .section-title')).toHaveText(['我的服务', '保持联系'])
  await page.getByRole('button', { name: '保存我的名片' }).click()
  await expect(page.getByRole('button', { name: '分享名片', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.locator('.profile-section .section-title')).toHaveText(['我的服务', '保持联系'])
  await page.getByRole('button', { name: '访客视角' }).click()
  const guest = await browser.newContext({ viewport: { width: 390, height: 844 } })
  try {
    const visitor = await guest.newPage()
    await visitor.goto(page.url())
    await expect(visitor.locator('.profile-section .section-title')).toHaveText(['我的服务', '保持联系'])
    await expect(visitor.locator('.section-content')).toHaveText('品牌策略\n网站与小程序设计', { useInnerText: true })
    await visitor.screenshot({ path: 'artifacts/profile-visitor-mobile.png', fullPage: true })
  }
  finally { await guest.close() }
  await page.getByRole('button', { name: '编辑我的名片', exact: true }).click()
  await openContinuousEditor(page)
  await expect(rows.nth(1)).toHaveAttribute('data-module-id', customId!)
  await expect(rows.nth(1).locator('textarea')).toHaveValue('品牌策略\n网站与小程序设计')
  await page.getByRole('button', { name: '显示模块 1', exact: true }).click()
  await page.getByRole('button', { name: '预览名片', exact: true }).click()
  await expect(page.locator('.profile-section .section-title')).toHaveText(['关于我', '我的服务', '保持联系'])
})

test('edit, reload, share, search, unbookmark and view analytics on mobile', async ({ page }) => {
  const errors: string[] = []
  await page.addInitScript(() => window.addEventListener('unhandledrejection', event => console.error('unhandled rejection', JSON.stringify(event.reason))))
  page.on('console', message => { if (message.type() === 'error') console.log('Browser:', message.text()) })
  page.on('pageerror', error => errors.push(error.message))
  page.on('response', async response => {
    if (response.url().includes('/api/') && response.status() >= 400)
      console.log('API failure:', response.status(), await response.text())
  })
  await page.goto('/')
  await expect(page.getByText('林予安', { exact: true })).toBeVisible()
  await expect(page.locator('body')).not.toContainText('无法连接服务')
  await page.getByRole('button', { name: '编辑名片', exact: true }).click()
  await openContinuousEditor(page, { appearance: true })
  await page.locator('.field').filter({ has: page.getByText(/^姓名\s*\*$/) }).locator('input').fill('许知行')
  await field(page, '联系电话').fill('13800000000')
  await field(page, '邮箱').fill('xuzhixing@example.com')
  await page.getByRole('button', { name: '深海蓝' }).click()
  await page.getByRole('button', { name: '保存我的名片' }).click()
  await expect(page.getByRole('button', { name: '分享名片', exact: true })).toBeVisible()
  await expect(page.getByText('许知行', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('许知行', { exact: true })).toBeVisible()
  await expect(page.locator('.identity-card')).toHaveClass(/ink/)
  await page.screenshot({ path: 'artifacts/home-mobile.png', fullPage: true })
  await page.getByRole('button', { name: '分享名片', exact: true }).click()
  await expect(page.locator('.qr-image')).toBeVisible()
  await expect(page.locator('.qr-image img')).toHaveAttribute('src', /^data:image\/png;base64/)
  await page.screenshot({ path: 'artifacts/share-mobile.png', fullPage: true })
  await page.getByRole('button', { name: '返回', exact: true }).click()
  await page.getByRole('button', { name: '名片夹', exact: true }).click()
  await expect(page.getByText('陈知远', { exact: true })).toBeVisible()
  await page.locator('.search-box input').fill('摄影')
  await page.getByRole('button', { name: '搜索', exact: true }).click()
  await expect(page.getByText('苏念', { exact: true })).toBeVisible()
  await expect(page.getByText('陈知远', { exact: true })).toHaveCount(0)
  await page.getByText('苏念', { exact: true }).click()
  await expect(page.getByRole('button', { name: '已收藏 · 点击取消' })).toBeVisible()
  await page.getByRole('button', { name: '已收藏 · 点击取消' }).click()
  await expect(page.getByRole('button', { name: '收藏这张名片' })).toBeVisible()
  await page.getByRole('button', { name: '返回', exact: true }).click()
  await expect(page.getByText('苏念', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '数据概览', exact: true }).click()
  await expect(page.getByText('近 7 天的连接足迹', { exact: true })).toBeVisible()
  await expect(page.getByText('自己的访问不计入。', { exact: false })).toBeVisible()
  await page.screenshot({ path: 'artifacts/stats-mobile.png', fullPage: true })
  expect(errors).toEqual([])
})

