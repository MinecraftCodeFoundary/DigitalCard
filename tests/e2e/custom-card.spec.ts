import { openContinuousEditor, openModuleSettings } from './helpers/editor'
import { test, expect } from '@playwright/test'

test('create a Card with mixed internal content, move it between pages and preserve it for visitors', async ({ page, browser }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '编辑名片', exact: true }).click()
  await openContinuousEditor(page, { pages: true })
  await page.getByRole('button', { name: '＋ 创建 Card', exact: true }).click()
  const card = page.locator('.module-row').nth(2)
  const editor = card.locator('.card-content-editor')
  await card.locator('input').first().fill('设计与交付')
  await expect(editor.getByText('这是一张空 Card，先添加一段文字或一组图片。')).toBeVisible()
  await editor.getByRole('button', { name: '＋ 添加文字', exact: true }).click()
  const blocks = editor.locator('.content-editor-block')
  await blocks.nth(0).locator('textarea').fill('品牌视觉\n让你的想法成为清晰的表达。')
  await editor.getByRole('button', { name: '内容 1 后插入图片', exact: true }).click()
  const photo = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 480; canvas.height = 320
    const ctx = canvas.getContext('2d')!; ctx.fillStyle = '#234e3e'; ctx.fillRect(0, 0, 480, 320)
    ctx.fillStyle = '#f4d35e'; ctx.beginPath(); ctx.arc(240, 160, 88, 0, Math.PI * 2); ctx.fill()
    return canvas.toDataURL('image/png').split(',')[1]
  })
  const chooser = page.waitForEvent('filechooser')
  await blocks.nth(1).getByRole('button', { name: '上传图片', exact: true }).click()
  await (await chooser).setFiles({ name: 'work.png', mimeType: 'image/png', buffer: Buffer.from(photo, 'base64') })
  await expect(blocks.nth(1).locator('.image-thumbnail')).toHaveCount(1)
  await expect(blocks.nth(1).getByRole('button', { name: '上传图片', exact: true })).toBeEnabled()
  await editor.getByRole('button', { name: '＋ 添加文字', exact: true }).click()
  await blocks.nth(2).locator('textarea').fill('从策略到设计，再到完整交付。\n我们一起完成下一件作品。')
  await editor.getByRole('button', { name: '＋ 添加链接', exact: true }).click()
  await blocks.nth(3).locator('input').nth(0).fill('https://example.com/portfolio')
  await blocks.nth(3).locator('input').nth(1).fill('了解合作方式')
  await blocks.nth(2).getByRole('button', { name: '上移内容 3', exact: true }).click()
  await expect(blocks.nth(1).locator('textarea')).toHaveValue('从策略到设计，再到完整交付。\n我们一起完成下一件作品。')
  await blocks.nth(1).getByRole('button', { name: '下移内容 2', exact: true }).click()
  await editor.getByRole('button', { name: '双列排版', exact: true }).click()
  await blocks.nth(0).getByRole('button', { name: '占一列', exact: true }).click()
  await blocks.nth(1).getByRole('button', { name: '占一列', exact: true }).click()
  await expect(page.locator('.module-row')).toHaveCount(3)
  await expect(blocks).toHaveCount(4)
  await page.getByRole('button', { name: '＋ 添加页面', exact: true }).click()
  await page.getByRole('button', { name: '第 2 页自由图文', exact: true }).click()
  await page.locator('.page-row').nth(1).locator('input').fill('作品与服务')
  await openModuleSettings(card)
  await card.getByRole('button', { name: '模块 3 放到第 2 页', exact: true }).click()
  await expect(page.locator('.module-group').nth(1).locator('.card-content-editor .content-editor-block')).toHaveCount(4)
  await page.getByRole('button', { name: '保存我的名片', exact: true }).click()
  await expect(page.getByRole('button', { name: '分享名片', exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: '访客视角', exact: true }).click()
  const guest = await browser.newContext({ viewport: { width: 390, height: 844 } })
  try {
    const visitor = await guest.newPage()
    await visitor.goto(page.url())
    await visitor.locator('.page-tabs').getByRole('button', { name: '作品与服务', exact: true }).click()
    const container = visitor.locator('.custom-card')
    await expect(container).toHaveCount(1)
    await expect(container.locator('.section-title')).toHaveText('设计与交付')
    await expect(container.locator('.card-content-block')).toHaveCount(4)
    await expect(container.locator('.block-text')).toHaveText(['品牌视觉\n让你的想法成为清晰的表达。', '从策略到设计，再到完整交付。\n我们一起完成下一件作品。'], { useInnerText: true })
    await expect(container.locator('.gallery-image img')).toHaveJSProperty('naturalWidth', 480)
    await expect(container.getByRole('button', { name: '了解合作方式', exact: true })).toBeVisible()
    const positions = await container.locator('.card-content-block').evaluateAll(elements => elements.map(element => { const rect = element.getBoundingClientRect(); return { x: rect.x, y: rect.y, width: rect.width } }))
    expect(Math.abs(positions[0].y - positions[1].y)).toBeLessThan(2)
    expect(positions[2].width).toBeGreaterThan(positions[0].width * 1.9)
    await expect(container).not.toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
    expect(await visitor.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await container.screenshot({ path: 'artifacts/custom-card-mobile.png' })
  }
  finally { await guest.close() }
  await page.getByRole('button', { name: '编辑我的名片', exact: true }).click()
  await openContinuousEditor(page, { pages: true })
  const restored = page.locator('.module-group').nth(1).locator('.card-content-editor')
  await expect(restored.locator('.content-editor-block')).toHaveCount(4)
  await expect(restored.locator('.content-editor-block').first().locator('textarea')).toHaveValue('品牌视觉\n让你的想法成为清晰的表达。')
  await page.getByRole('button', { name: '编辑第 2 页', exact: true }).click()
  await page.getByRole('button', { name: '隐藏模块 3', exact: true }).click()
  await page.getByRole('button', { name: '预览名片', exact: true }).click()
  await expect(page.locator('.live-preview .custom-card')).toHaveCount(0)
  await page.getByRole('button', { name: '显示模块 3', exact: true }).click()
  await expect(page.locator('.live-preview .custom-card .card-content-block')).toHaveCount(4)
})
