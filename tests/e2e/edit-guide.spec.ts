test('an invalid hidden Card subtitle is revealed without opening unrelated layout controls', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '编辑名片', exact: true }).click()
  await step(page, 2, '业务与展示').click()
  await page.getByRole('button', { name: '页面与排版设置', exact: true }).click()
  await page.getByRole('button', { name: '＋ 创建 Card', exact: true }).click()
  const card = page.locator('.module-row').last()
  await card.getByRole('button', { name: '＋ 添加文字', exact: true }).click()
  const blocks = card.locator('.content-editor-block')
  await blocks.first().locator('textarea').fill('标题隐藏时，这段内容也应能保存。')
  await blocks.first().getByRole('button', { name: '内容 1 标题设置', exact: true }).click()
  await expect(blocks.first().getByRole('button', { name: '隐藏小标题', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await blocks.first().locator('input').fill('')
  await blocks.first().getByRole('button', { name: '内容 1 标题设置', exact: true }).click()
  await card.getByRole('button', { name: '＋ 添加文字', exact: true }).click()
  await blocks.last().locator('textarea').fill('另一段内容保持不变。')
  await page.getByRole('button', { name: '收起页面与排版设置', exact: true }).click()
  await step(page, 3, '风格与发布').click()
  await page.getByRole('button', { name: '保存我的名片', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('请填写 Card 内容的小标题，或使用默认名称')
  await expect(step(page, 2, '业务与展示')).toHaveAttribute('aria-current', 'step')
  await expect(blocks.first()).toBeInViewport()
  await expect(blocks.first().getByRole('button', { name: '内容 1 标题设置', exact: true })).toHaveAttribute('aria-expanded', 'true')
  await expect(blocks.last().getByRole('button', { name: '内容 2 标题设置', exact: true })).toHaveAttribute('aria-expanded', 'false')
  await expect(page.locator('.page-row')).toBeHidden()
  await blocks.first().locator('input').fill('服务说明')
  await expect(blocks.first().getByRole('button', { name: '隐藏小标题', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await step(page, 3, '风格与发布').click()
  await page.getByRole('button', { name: '保存我的名片', exact: true }).click()
  await expect(page.getByRole('button', { name: '分享名片', exact: true })).toBeVisible()
})
