import { openContinuousEditor, openModuleSettings } from './helpers/editor'
import { test, expect } from '@playwright/test'

test('organize named pages and columns, publish them and preserve modules when deleting a page', async ({ page, browser }) => {
  test.setTimeout(90000)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/')
  await page.getByRole('button', { name: '编辑名片', exact: true }).click()
  await openContinuousEditor(page, { pages: true })
  await page.getByRole('button', { name: '＋ 添加页面', exact: true }).click()
  const pages = page.locator('.page-row')
  const rows = page.locator('.module-row')
  await expect(pages).toHaveCount(2)
  await pages.nth(1).locator('input').fill('作品与服务')
  await page.getByRole('button', { name: '第 2 页图标图片', exact: true }).click()
  await page.getByRole('button', { name: '第 2 页双栏', exact: true }).click()
  for (const [index, title] of ['品牌设计', '网站开发', '合作方式'].entries()) {
    await page.locator('.module-group').nth(1).getByRole('button', { name: '＋ 添加文字段落', exact: true }).click()
    await rows.nth(index + 2).locator('input').fill(title)
    await rows.nth(index + 2).locator('textarea').fill(`${title}内容\n欢迎联系我`)
  }
  await openModuleSettings(rows.nth(4))
  await page.getByRole('button', { name: '模块 5 通栏', exact: true }).click()
  const preview = page.locator('.live-preview')
  await expect(preview.locator('.page-tabs .i-carbon-image')).toHaveCount(1)
  await expect(preview.locator('.page-tabs .i-carbon-image')).not.toHaveCSS('mask-image', 'none')
  await expect(preview.locator('.profile-section .section-title')).toHaveText(['品牌设计', '网站开发', '合作方式'])
  await expect(preview.locator('.section-grid')).toHaveClass(/columns-two/)
  await openModuleSettings(rows.nth(1))
  await page.getByRole('button', { name: '模块 2 放到第 2 页', exact: true }).click()
  await expect(preview.locator('.profile-section .section-title')).toHaveText(['保持联系', '品牌设计', '网站开发', '合作方式'])
  await page.getByRole('button', { name: '模块 2 放到第 1 页', exact: true }).click()
  await page.getByRole('button', { name: '前移第 2 页', exact: true }).click()
  await expect(pages.nth(0).locator('input')).toHaveValue('作品与服务')
  await expect.poll(() => rows.locator('input').evaluateAll(inputs => inputs.map(input => (input as HTMLInputElement).value))).toEqual(['品牌设计', '网站开发', '合作方式', '关于我', '保持联系'])
  await page.getByRole('button', { name: '后移第 1 页', exact: true }).click()
  await expect.poll(() => rows.locator('input').evaluateAll(inputs => inputs.map(input => (input as HTMLInputElement).value))).toEqual(['关于我', '保持联系', '品牌设计', '网站开发', '合作方式'])
  await page.screenshot({ path: 'artifacts/pages-editor-desktop.png', fullPage: true })
  await page.getByRole('button', { name: '保存我的名片' }).click()
  await expect(page.getByRole('button', { name: '分享名片', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.locator('.profile-section .section-title')).toHaveText(['关于我', '保持联系'])
  await page.getByRole('button', { name: '访客视角', exact: true }).click()
  const guest = await browser.newContext({ viewport: { width: 390, height: 844 } })
  try {
    const visitor = await guest.newPage()
    await visitor.goto(page.url())
    await expect(visitor.locator('.page-tabs .i-carbon-image')).toBeVisible()
    await expect(visitor.locator('.page-tabs .i-carbon-image')).not.toHaveCSS('mask-image', 'none')
    await visitor.locator('.page-tabs').getByRole('button', { name: '作品与服务', exact: true }).click()
    const modules = visitor.locator('.profile-section')
    await expect(modules.locator('.section-title')).toHaveText(['品牌设计', '网站开发', '合作方式'])
    const first = await modules.nth(0).boundingBox()
    const second = await modules.nth(1).boundingBox()
    const full = await modules.nth(2).boundingBox()
    expect(first).not.toBeNull()
    expect(second).not.toBeNull()
    expect(full).not.toBeNull()
    expect(Math.abs(first!.y - second!.y)).toBeLessThan(2)
    expect(full!.width).toBeGreaterThan(first!.width * 1.9)
    expect(await visitor.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await visitor.screenshot({ path: 'artifacts/pages-visitor-mobile.png', fullPage: true })
    await visitor.getByRole('button', { name: '上一页', exact: true }).click()
    await expect(modules.locator('.section-title')).toHaveText(['关于我', '保持联系'])
    await visitor.getByRole('button', { name: '下一页', exact: true }).click()
    await expect(modules.locator('.section-title')).toHaveText(['品牌设计', '网站开发', '合作方式'])
    await visitor.setViewportSize({ width: 1440, height: 1000 })
    await visitor.screenshot({ path: 'artifacts/pages-visitor-desktop.png', fullPage: true })
  }
  finally { await guest.close() }
  await page.getByRole('button', { name: '编辑我的名片', exact: true }).click()
  await openContinuousEditor(page, { pages: true })
  await expect(pages.nth(1).locator('input')).toHaveValue('作品与服务')
  await expect(page.getByRole('button', { name: '第 2 页双栏', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: '删除第 2 页', exact: true }).click()
  await expect(pages).toHaveCount(1)
  await expect(rows).toHaveCount(5)
  await expect(rows.nth(2).locator('textarea')).toHaveValue('品牌设计内容\n欢迎联系我')
  await expect(preview.locator('.profile-section .section-title')).toHaveText(['关于我', '保持联系', '品牌设计', '网站开发', '合作方式'])
  await expect(page.getByRole('button', { name: '删除第 1 页', exact: true })).toHaveAttribute('aria-disabled', 'true')
  await page.getByRole('button', { name: '保存我的名片' }).click()
  await expect(page.getByRole('button', { name: '分享名片', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.locator('.page-tabs')).toHaveCount(0)
  await expect(page.locator('.profile-section .section-title')).toHaveText(['关于我', '保持联系', '品牌设计', '网站开发', '合作方式'])
})
