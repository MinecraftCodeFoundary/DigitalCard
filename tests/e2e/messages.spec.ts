import { test, expect } from '@playwright/test'

test('mobile visitors leave a private message at the bottom and the owner receives it', async ({ page, browser }) => {
  await page.goto('/')
  await expect(page.getByRole('button', { name: '编辑名片', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '访客视角', exact: true }).click()
  await expect(page.locator('.message-board .section-title')).toHaveText('收到的留言')
  const guest = await browser.newContext({ viewport: { width: 390, height: 844 } })
  try {
    const visitor = await guest.newPage()
    await visitor.goto(page.url())
    const board = visitor.locator('.message-board')
    await expect(board.locator('.section-title')).toHaveText('给我留言')
    const bottom = await visitor.locator('.detail-grid').evaluate(element => element.lastElementChild?.lastElementChild?.classList.contains('message-board'))
    expect(bottom).toBe(true)
    await expect(board.getByRole('button', { name: '刷新留言', exact: true })).toHaveCount(0)
    await board.getByRole('button', { name: '发送留言', exact: true }).click()
    await expect(board.getByRole('alert')).toHaveText('请填写你的称呼')
    await board.locator('.message-name-input input').fill('陈小雨')
    await board.locator('.message-contact-input input').fill('hello@example.com')
    await board.locator('textarea').fill('想聊聊新品牌的设计。\n下周方便交流吗？')
    await board.scrollIntoViewIfNeeded()
    expect(await visitor.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await board.screenshot({ path: 'artifacts/message-board-mobile.png' })
    await board.getByRole('button', { name: '发送留言', exact: true }).click()
    await expect(board.getByText('留言已送达', { exact: true })).toBeVisible()
    await visitor.reload()
    await expect(visitor.locator('.message-item')).toHaveCount(0)
    await expect(visitor.locator('body')).not.toContainText('hello@example.com')
    const ownerBoard = page.locator('.message-board')
    await ownerBoard.getByRole('button', { name: '刷新留言', exact: true }).click()
    await expect(ownerBoard.locator('.message-name')).toHaveText('陈小雨')
    await expect(ownerBoard.locator('.message-content')).toHaveText('想聊聊新品牌的设计。\n下周方便交流吗？', { useInnerText: true })
    await expect(ownerBoard.locator('.message-contact')).toContainText('hello@example.com')
    await page.goto('/')
    await expect(page.locator('.message-board .message-name')).toHaveText('陈小雨')
    await page.reload()
    await expect(page.locator('.message-board .message-name')).toHaveText('陈小雨')
    await page.locator('.message-board').screenshot({ path: 'artifacts/message-inbox-mobile.png' })
  }
  finally { await guest.close() }
})
