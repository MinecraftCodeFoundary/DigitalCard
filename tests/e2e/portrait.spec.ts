import { openContinuousEditor, openModuleSettings } from './helpers/editor'
import { test, expect, type Locator, type Page } from '@playwright/test'

async function upload(page: Page, button: Locator, files: { name: string, mimeType: string, buffer: Buffer }[]) {
  const chooser = page.waitForEvent('filechooser')
  await button.click()
  await (await chooser).setFiles(files)
}

test('build a portrait homepage with icon navigation and independent company article', async ({ page, browser }) => {
  test.setTimeout(90000)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/')
  const fixtures = await page.evaluate(() => {
    const canvas = document.createElement('canvas')
    canvas.width = 480; canvas.height = 720
    const context = canvas.getContext('2d')!
    const gradient = context.createLinearGradient(0, 0, 480, 720)
    gradient.addColorStop(0, '#8fe7f3'); gradient.addColorStop(1, '#358dcc')
    context.fillStyle = gradient; context.fillRect(0, 0, 480, 720)
    context.fillStyle = '#ffffff22'; context.fillRect(90, 100, 300, 380)
    context.fillStyle = 'white'; context.font = '32px sans-serif'; context.fillText('PORTRAIT COVER', 80, 150)
    const portrait = canvas.toDataURL('image/png').split(',')[1]
    canvas.width = 480; canvas.height = 280
    context.fillStyle = '#d9edf5'; context.fillRect(0, 0, 480, 280)
    context.fillStyle = '#2778a0'; context.font = '28px sans-serif'; context.fillText('COMPANY / STUDIO', 75, 140)
    return { portrait, company: canvas.toDataURL('image/png').split(',')[1] }
  })
  await page.getByRole('button', { name: '编辑名片', exact: true }).click()
  await openContinuousEditor(page, { appearance: true, pages: true })
  await page.getByRole('button', { name: '人物主页', exact: false }).click()
  await expect(page.locator('.page-row')).toHaveCount(4)
  const preview = page.locator('.live-preview')
  await expect(preview.locator('.homepage-nav-item')).toHaveCount(4)
  await expect(preview.locator('.homepage-nav-item')).toHaveText(['个人简介', '公司简介', '产品服务', '联系我们'])
  const cover = page.locator('.portrait-cover-editor')
  await upload(page, cover.getByRole('button', { name: '上传人物封面', exact: true }), [{ name: 'portrait.png', mimeType: 'image/png', buffer: Buffer.from(fixtures.portrait, 'base64') }])
  await expect(preview.locator('.portrait-photo img')).toHaveJSProperty('naturalWidth', 480)
  await page.getByRole('button', { name: '第 2 页图标图片', exact: true }).click()
  await page.getByRole('button', { name: '编辑第 2 页', exact: true }).click()
  await page.locator('.module-group[data-page-id="company"]').getByRole('button', { name: '＋ 添加图片模块', exact: true }).click()
  const gallery = page.locator('.module-group[data-page-id="company"] .module-row').first()
  await openModuleSettings(gallery)
  await gallery.locator('input').first().fill('公司环境')
  const company = { name: 'company.png', mimeType: 'image/png', buffer: Buffer.from(fixtures.company, 'base64') }
  await upload(page, gallery.getByRole('button', { name: '上传图片', exact: true }), [company, { ...company, name: 'factory.png' }])
  await expect(gallery.locator('.image-thumbnail')).toHaveCount(2)
  await gallery.getByRole('button', { name: '纵向展示', exact: true }).click()
  await gallery.locator('textarea').fill('我们的公司专注于产品研发与专业服务。\n欢迎了解我们的团队与合作方式。')
  await expect(preview.locator('.homepage-page-heading')).toHaveText('公司简介')
  await expect(preview.locator('.section-title')).toHaveCount(0)
  await expect(preview.locator('.gallery-image')).toHaveCount(2)
  await page.getByRole('button', { name: '保存我的名片', exact: true }).click()
  await expect(page.getByRole('button', { name: '分享名片', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.locator('.homepage-nav-item')).toHaveCount(4)
  await page.getByRole('button', { name: '访客视角', exact: true }).click()
  const guest = await browser.newContext({ viewport: { width: 390, height: 844 } })
  try {
    const visitor = await guest.newPage()
    await visitor.goto(page.url())
    await expect(visitor.locator('.portrait-photo img')).toHaveJSProperty('naturalWidth', 480)
    await expect(visitor.locator('.brand')).toHaveCount(0)
    await expect(visitor.locator('.identity-card')).toHaveCSS('border-radius', '0px')
    await expect(visitor.getByRole('button', { name: '收藏这张名片', exact: true })).toHaveCSS('background-color', 'rgb(88, 189, 233)')
    await expect(visitor.locator('.homepage-nav-item').nth(1).locator('.i-carbon-image')).toHaveCount(1)
    await visitor.screenshot({ path: 'artifacts/portrait-homepage-mobile.png', fullPage: true })
    await visitor.getByRole('button', { name: '打开公司简介', exact: true }).click()
    await expect(visitor.locator('.portrait-hero')).toHaveCount(0)
    await expect(visitor.locator('.homepage-page-heading')).toHaveText('公司简介')
    await expect(visitor.locator('.homepage-page-body .section-title')).toHaveCount(0)
    await expect(visitor.locator('.message-board .section-title')).toHaveText('给我留言')
    await expect(visitor.locator('.gallery-image')).toHaveCount(2)
    await expect(visitor.locator('.gallery-image img').first()).toHaveJSProperty('naturalWidth', 480)
    const images = visitor.locator('.gallery-image')
    const first = await images.nth(0).boundingBox()
    const second = await images.nth(1).boundingBox()
    expect(second!.y).toBeGreaterThan(first!.y + first!.height)
    await expect(visitor.locator('.media-caption')).toContainText('我们的公司专注于产品研发')
    await expect(visitor.locator('.profile-section')).toHaveCSS('border-top-width', '0px')
    expect(await visitor.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await visitor.screenshot({ path: 'artifacts/portrait-company-mobile.png', fullPage: true })
    await visitor.getByRole('button', { name: '返回名片首页', exact: true }).click()
    await expect(visitor.locator('.portrait-hero')).toBeVisible()
    await visitor.getByRole('button', { name: '打开联系我们', exact: true }).click()
    await expect(visitor.locator('.homepage-page-heading')).toHaveText('联系我们')
    await expect(visitor.locator('.contact-row')).toHaveCount(0)
    await visitor.getByRole('button', { name: '返回名片首页', exact: true }).click()
  }
  finally { await guest.close() }
  await page.getByRole('button', { name: '编辑我的名片', exact: true }).click()
  await openContinuousEditor(page, { appearance: true, pages: true })
  await expect(cover.locator('input')).toHaveValue(/\/api\/media\/[a-f\d]{24}/)
  await expect(page.locator('.page-row').nth(1).getByRole('button', { name: '第 2 页自由图文' })).toHaveAttribute('aria-pressed', 'true')
})
